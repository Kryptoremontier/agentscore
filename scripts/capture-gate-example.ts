/**
 * Writes src/lib/gate-example.ts: one real trust-gate answer (Captain Dackie, minPeople 1 in
 * Crypto / Onchain), one real answer per id form the gate takes (Etap 9) and the paste-able
 * snippet, for /llms.txt, SKILL.md and /docs — never hand-typed. Re-run after a change to the gate's answer or to examples/trust-gate.ts:
 *   AGENTSCORE_URL=http://localhost:3000 node --experimental-strip-types scripts/capture-gate-example.ts
 * then `node --experimental-strip-types scripts/write-skill-gate.ts` (SKILL.md's copy of the examples).
 * gate-example.test.ts checks the snippet is byte-identical and that the gate still emits this answer.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const BASE = (process.env.AGENTSCORE_URL ?? 'https://agentscore-gilt.vercel.app').replace(/\/$/, '')
const DACKIE = '0x45078ae569def2264355f77e592028dd6f1f5d6373c204fe82bf3141ab1861fb'
const request = `/api/v1/agents/${DACKIE}/gate?minPeople=1&area=Crypto%20%2F%20Onchain`

// Our own calls: not counted as outside gate calls (stats gateCalls7d, lib/gate-calls.ts).
const OURS = { headers: { 'X-AgentScore-Internal': '1' } }
const res = await fetch(`${BASE}${request}`, OURS)
const answer = await res.json()
if (!res.ok || answer?.data?.decision !== 'allow') throw new Error(`unexpected answer: HTTP ${res.status} ${JSON.stringify(answer)}`)
const snippet = readFileSync('examples/trust-gate.ts', 'utf8')

// Etap 9 — the gate takes any id: one real answer per id form, all under ?minPeople=1.
const FORMS: Array<{ form: string; id: string }> = [
  { form: 'Intuition term id', id: DACKIE },
  { form: 'ERC-8004 id (chain:token)', id: '8453:1380' },
  { form: 'ERC-8004 id (CAIP)', id: process.env.GATE_EXAMPLE_CAIP ?? 'eip155:8453/erc721:0x8004a169fb4a3325136eb29fa0ceb6d2e539a432/1380' },
  { form: 'exact name', id: 'Captain Dackie' },
  { form: 'wallet that registered the agent', id: process.env.GATE_EXAMPLE_WALLET ?? '0x139219107C1eBE569f543C581b3B807Cf6740006' },
]
const idExamples: Array<{ form: string; id: string; request: string; data: unknown }> = []
for (const { form, id } of FORMS) {
  const idRequest = `/api/v1/agents/${encodeURIComponent(id)}/gate?minPeople=1`
  const r = await fetch(`${BASE}${idRequest}`, OURS)
  const body = await r.json()
  if (!r.ok || !body?.data?.decision) throw new Error(`${form}: HTTP ${r.status} ${JSON.stringify(body)}`)
  // A failed read is not an example of anything: capture again when the indexer answers.
  if (body.data.decision === 'unknown' && !body.data.candidates) throw new Error(`${form}: unknown (${body.data.reason})`)
  idExamples.push({ form, id, request: idRequest, data: body.data })
}

writeFileSync('src/lib/gate-example.ts', `/**
 * GENERATED by scripts/capture-gate-example.ts — do not edit by hand.
 * One real trust-gate answer (captured ${answer.meta.timestamp} from ${BASE}) and the snippet in
 * examples/trust-gate.ts, for /llms.txt, SKILL.md and /docs. gate-example.test.ts checks both.
 */

export const EXAMPLE_GATE = {
  agent: 'Captain Dackie',
  request: ${JSON.stringify(request)},
  answer: ${JSON.stringify(answer, null, 2).replace(/\n/g, '\n  ')},
} as const

/** Etap 9 — the gate takes any id: one real answer (\`data\`) per id form, captured in the same run. */
export const GATE_ID_EXAMPLES = ${JSON.stringify(idExamples, null, 2)} as const

export const GATE_SNIPPET = ${JSON.stringify(snippet)}
`)
console.log(`wrote src/lib/gate-example.ts (${answer.data.decision}, data ${answer.data.meta.dataAgeSeconds} s old; ${idExamples.length} id forms)`)
