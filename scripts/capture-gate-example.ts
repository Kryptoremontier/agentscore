/**
 * Writes src/lib/gate-example.ts: one real trust-gate answer (Captain Dackie, minPeople 1 in
 * Crypto / Onchain), for /llms.txt, SKILL.md and /docs — never hand-typed. Re-run after a change
 * to the gate's answer:
 *   AGENTSCORE_URL=http://localhost:3000 node --experimental-strip-types scripts/capture-gate-example.ts
 * gate-example.test.ts checks that the gate still emits this answer.
 */
import { writeFileSync } from 'node:fs'

const BASE = (process.env.AGENTSCORE_URL ?? 'https://agentscore-gilt.vercel.app').replace(/\/$/, '')
const DACKIE = '0x45078ae569def2264355f77e592028dd6f1f5d6373c204fe82bf3141ab1861fb'
const request = `/api/v1/agents/${DACKIE}/gate?minPeople=1&area=Crypto%20%2F%20Onchain`

const res = await fetch(`${BASE}${request}`)
const answer = await res.json()
if (!res.ok || answer?.data?.decision !== 'allow') throw new Error(`unexpected answer: HTTP ${res.status} ${JSON.stringify(answer)}`)

writeFileSync('src/lib/gate-example.ts', `/**
 * GENERATED by scripts/capture-gate-example.ts — do not edit by hand.
 * One real trust-gate answer (captured ${answer.meta.timestamp} from ${BASE}),
 * for /llms.txt, SKILL.md and /docs. gate-example.test.ts checks it.
 */

export const EXAMPLE_GATE = {
  agent: 'Captain Dackie',
  request: ${JSON.stringify(request)},
  answer: ${JSON.stringify(answer, null, 2).replace(/\n/g, '\n  ')},
} as const
`)
console.log(`wrote src/lib/gate-example.ts (${answer.data.decision}, data ${answer.data.meta.dataAgeSeconds} s old)`)
