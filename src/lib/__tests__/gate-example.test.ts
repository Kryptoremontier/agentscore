/**
 * Etap 7 — the trust gate's example answer on /llms.txt, SKILL.md and /docs is a real response
 * (captured by scripts/capture-gate-example.ts into lib/gate-example.ts), never hand-typed, and
 * the code still emits it: the same decision for the same live-shaped attestations.
 */
import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { EXAMPLE_GATE } from '../gate-example'
import { decideTrustGate, parseGatePolicy } from '../trust-gate'
import { aggregateAttestations } from '../attestation-reader'

const DACKIE = '0x45078ae569def2264355f77e592028dd6f1f5d6373c204fe82bf3141ab1861fb'
const CRYPTO = '0xecc2b1dce5f8269777d9001faa532642691d7038eed3c639f04895ac5b312d42'

describe('the captured example', () => {
  it('is Captain Dackie under minPeople 1 in Crypto / Onchain, a real REST answer with its data age', () => {
    expect(EXAMPLE_GATE.request).toBe(`/api/v1/agents/${DACKIE}/gate?minPeople=1&area=Crypto%20%2F%20Onchain`)
    expect(EXAMPLE_GATE.answer.success).toBe(true)
    expect(EXAMPLE_GATE.answer.data.meta).toEqual({ dataAgeSeconds: EXAMPLE_GATE.answer.meta.dataAgeSeconds, dataReadAt: EXAMPLE_GATE.answer.meta.dataReadAt })
  })

  it('is what the gate emits for the attestations behind it (one person, 0.0099 tTRUST in Crypto / Onchain)', () => {
    const q = new URLSearchParams(EXAMPLE_GATE.request.split('?')[1])
    const parsed = parseGatePolicy({ minPeople: q.get('minPeople'), area: q.get('area') })
    if (!parsed.ok) throw new Error(parsed.error)
    const attested = aggregateAttestations([{
      tripleId: '0xe8565630aee28d221ca6e33461ca76faaa2e20e8865b0e9be2fbd8875186f906', agentId: DACKIE, agentName: 'Captain Dackie', domainTermId: CRYPTO,
      supportPositions: [{ wallet: '0x139219107C1eBE569f543C581b3B807Cf6740006', shares: 9_900_000_000_000_000n }], opposePositions: [],
    }])
    expect(decideTrustGate({ status: 'found', attested }, parsed.policy, EXAMPLE_GATE.answer.data.meta)).toEqual(EXAMPLE_GATE.answer.data)
  })

  it('is the generated module, not a hand edit', () => {
    expect(readFileSync('src/lib/gate-example.ts', 'utf8')).toMatch(/^\/\*\*\n \* GENERATED by scripts\/capture-gate-example\.ts/)
  })
})

describe('every surface shows that answer', () => {
  it('/llms.txt', async () => {
    const { GET } = await import('@/app/llms.txt/route')
    const text = await (await GET()).text()
    expect(text).toContain(`Real answer (GET ${EXAMPLE_GATE.request}):\n${JSON.stringify(EXAMPLE_GATE.answer)}`)
    expect(text).toContain('should_i_trust')
    expect(text).toMatch(/"unknown" = the data couldn't be read right now\. Treat it as NO/)
  })

  it('SKILL.md', () => {
    const skill = readFileSync('SKILL.md', 'utf8')
    expect(skill).toContain(`curl "https://agentscore-gilt.vercel.app${EXAMPLE_GATE.request}"`)
    expect(skill).toContain(JSON.stringify(EXAMPLE_GATE.answer, null, 2))
    expect(skill).toMatch(/treat it as no — do not pay or delegate/)
  })

  it('/docs renders it from the module', () => {
    const docs = readFileSync('src/app/docs/page.tsx', 'utf8')
    expect(docs).toContain("import { EXAMPLE_GATE } from '@/lib/gate-example'")
    expect(docs).toContain('{JSON.stringify(EXAMPLE_GATE.answer, null, 2)}')
  })
})

